// `em api generate` (MIL-237, promoted from the MIL-159 `em typespec` POC): the model-owned
// contract for a model's `public` surface, as TypeSpec (https://typespec.io) source text —
// plain `model`/`interface`/`op` declarations, core scalars only, no imports, no decorators,
// no `@versioned` (one release train; versions are Backlog).
//
//  - public commands -> `model` (payload) + `interface Commands { op <name>(payload: <Model>): void; }`
//    (the write API; GH #445 — same payload-model shape as events/views, so field notes and
//    `INV-*` lines ride along and the payload is decoratable by a binding file's `@@`)
//  - public events   -> `model` (async payload) + `interface Events { op on<Event>(payload): void; }`
//    (GH #446 — one op per public event, so a binding file has a declaration to `@@channel`/
//    `@@publish` against instead of re-stating the payload shape)
//  - public views    -> `model` + `interface Views { op get<View>(): <View>; }` (the read API)
//  - declared `type`s reachable from any of those -> `model`
//
// Types map through ONE fixed table (`PUBLIC_SCALAR_TYPES`, src/model/model.ts — briefing R7)
// or a declared `type`; there is no alias map, no generic-wrapper handling and no `unknown`
// fallback. `em validate`'s `public-field-type-unresolved` guarantees every field on this
// surface resolves, and the CLI refuses to generate from a model with errors, so an
// unresolvable type here is a programming error, not a user-facing case.
//
// Reuses `buildExportDoc` (emit/json.ts) so `public`/`optional`/`typeRef`/tags/renamedFrom are
// resolved once, the same way `em export` resolves them. Deterministic: no timestamps, no git
// data, no absolute paths — the `Source:` line is whatever label the caller passes (the CLI
// passes the model path relative to the contract file's own directory). Deliberately NO source
// hash (R12 amended): the text depends only on the public surface, so an internal-only `.em`
// edit leaves the contract byte-identical and neither CODEOWNERS routing nor the API-first
// gate fires on it.

import { NormalizedModel, PUBLIC_SCALAR_TYPE_NAMES, PUBLIC_SCALAR_TYPES, resolvePublicType } from "../model/model.js";
import { RefsResult } from "../model/refs.js";
import { Diagnostic } from "../model/validate.js";
import { dedupe } from "../util/slug.js";
import { buildExportDoc, ElementExport, FieldExport, TypeExport } from "./json.js";

/** The sentence every generated `model` carries (MIL-239 relies on it verbatim). */
export const CONSUMER_TOLERANCE_SENTENCE = "Consumers tolerate unknown fields; additive changes do not break them.";

export const API_HEADER_LINE = "// GENERATED by em api generate — do not hand-edit.";

export interface ApiContractResult {
  /** TypeSpec source text, no trailing newline. */
  text: string;
  /** Same diagnostics `buildExport` would raise for this model. */
  diagnostics: Diagnostic[];
}

/** em element/type names are free text; TypeSpec model/interface names are PascalCase. */
function pascalCase(name: string): string {
  const words = name.match(/[A-Za-z0-9]+/g) ?? [];
  const joined = words.map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  if (joined.length === 0) return "Unnamed";
  return /^[0-9]/.test(joined) ? `_${joined}` : joined;
}

function camelCase(pascal: string): string {
  return pascal.length > 0 ? pascal[0].toLowerCase() + pascal.slice(1) : pascal;
}

/** Declared types reachable (transitively) from any of the given elements' fields, as the set of
 *  their export refs — same walk `em api generate`'s contract body and `em api surface` (GH #448)
 *  use to decide which declared types belong on the public surface, shared so neither re-derives
 *  it with a subtly different recursion. */
export function reachableTypeRefs(
  elements: { fields: FieldExport[] | null }[],
  typesByRef: Map<string, TypeExport>,
): Set<string> {
  const reachable = new Set<string>();
  const walk = (fields: FieldExport[] | null) => {
    for (const f of fields ?? []) {
      if (f.typeRef && !reachable.has(f.typeRef.ref)) {
        reachable.add(f.typeRef.ref);
        walk(typesByRef.get(f.typeRef.ref)?.fields ?? null);
      }
    }
  };
  for (const el of elements) walk(el.fields);
  return reachable;
}

/** Declared identity scalars (GH #477) reachable from any of the given elements' fields,
 *  directly or through a reachable declared type's own fields — the scalar-namespace sibling of
 *  `reachableTypeRefs` above, same "no dead declarations" rule (#444's rule extended to GH #477):
 *  only a scalar some field on the public surface actually uses gets declared. Scalars have no
 *  fields of their own (always a leaf alias over a table entry), so there's no recursion through
 *  a scalar itself — only through the declared types `reachableTypeRefs` already walks. Shared
 *  with `em api surface` (`cli/api.ts`'s `buildApiSurfaceReport`), same reasoning as
 *  `reachableTypeRefs`. */
export function reachableScalarRefs(
  elements: { fields: FieldExport[] | null }[],
  typesByRef: Map<string, TypeExport>,
): Set<string> {
  const reachable = new Set<string>();
  const seenTypes = new Set<string>();
  const walk = (fields: FieldExport[] | null) => {
    for (const f of fields ?? []) {
      if (f.scalarRef) reachable.add(f.scalarRef.ref);
      if (f.typeRef && !seenTypes.has(f.typeRef.ref)) {
        seenTypes.add(f.typeRef.ref);
        walk(typesByRef.get(f.typeRef.ref)?.fields ?? null);
      }
    }
  };
  for (const el of elements) walk(el.fields);
  return reachable;
}

/** Declared enums (GH #478) reachable from any of the given elements' fields, directly or
 *  through a reachable declared type's own fields — the enum-namespace sibling of
 *  `reachableScalarRefs` above, same "no dead declarations" rule. Enums have no fields of their
 *  own either, so there's no recursion through an enum itself. Shared with `em api surface`. */
export function reachableEnumRefs(
  elements: { fields: FieldExport[] | null }[],
  typesByRef: Map<string, TypeExport>,
): Set<string> {
  const reachable = new Set<string>();
  const seenTypes = new Set<string>();
  const walk = (fields: FieldExport[] | null) => {
    for (const f of fields ?? []) {
      if (f.enumRef) reachable.add(f.enumRef.ref);
      if (f.typeRef && !seenTypes.has(f.typeRef.ref)) {
        seenTypes.add(f.typeRef.ref);
        walk(typesByRef.get(f.typeRef.ref)?.fields ?? null);
      }
    }
  };
  for (const el of elements) walk(el.fields);
  return reachable;
}

/** A field name that isn't a bare TypeSpec identifier is backtick-quoted (TypeSpec's own escape). */
function fieldIdentifier(name: string): string {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) return name;
  return "`" + name.replace(/\\/g, "\\\\").replace(/`/g, "\\`") + "`";
}

/** GH #478: an enum member that is itself a bare TypeSpec identifier emits unquoted (`placed`);
 *  anything else — a dash, a space, a leading digit, punctuation — emits as a quoted string
 *  literal instead (`"out-of-stock"`), TypeSpec's own enum string-member form (verified against
 *  the installed @typespec/compiler; see REPORT.md's probe: `enum X { "a-b", c }` compiles).
 *  Unlike `fieldIdentifier` above, there is no backtick escape for an enum member — a non-
 *  identifier member is always a plain value, never a name that needs quoting-as-identifier. */
function enumMemberText(member: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(member) ? member : JSON.stringify(member);
}

// `tag`, `renamed from` and `assigned` are modeling concerns, not wire shape — carried as doc
// comments, never decorators (a decorator would need its own TypeSpec library).
function fieldNotes(f: FieldExport): string | null {
  const notes: string[] = [];
  if (f.tag) notes.push("DCB identity tag");
  if (f.renamedFrom && f.renamedFrom.length > 0) {
    notes.push(`renamed from ${f.renamedFrom.map((n) => JSON.stringify(n)).join(", ")}`);
  }
  if (f.assigned) notes.push("system-assigned — not supplied by the triggering command");
  return notes.length > 0 ? notes.join("; ") : null;
}

function elementNotes(el: ElementExport): string[] {
  const notes: string[] = [];
  if (el.renamedFrom && el.renamedFrom.length > 0) {
    notes.push(`renamed from ${el.renamedFrom.map((n) => JSON.stringify(n)).join(", ")}`);
  }
  for (const t of el.tags ?? []) {
    if (t.kind === "composite") notes.push(`DCB composite tag \`${t.key}\` from ${(t.fields ?? []).join(", ")}`);
    else if (t.kind === "external") notes.push(`DCB external tag \`${t.key}\`: ${t.description}`);
  }
  return notes;
}

/** MIL-265: a public element's model-declared invariants, one `/** INV-X: rule *\/` line each in
 *  declaration order — part of the contract, so tightening a rule changes the committed file
 *  (and `em api check` annotates it). A `*\/` inside the rule text is escaped so the comment
 *  cannot close early. */
function invariantLines(el: ElementExport): string[] {
  return (el.invariants ?? []).map((inv) =>
    inv.rule === null ? `/** ${inv.id} */` : `/** ${inv.id}: ${inv.rule.replace(/\*\//g, "*\\/")} */`,
  );
}

function indent(lines: string[], depth: number): string[] {
  const pad = "  ".repeat(depth);
  return lines.map((l) => (l.length > 0 ? pad + l : l));
}

/** The public elements `em api` covers, in export (timeline) order. A repeated view
 *  (`view X again`) contributes its first public instance only — one logical read model,
 *  one TypeSpec declaration. Shared with `em api check` so both read the same surface. */
export function publicSurfaceOf(slices: { elements: ElementExport[] }[]): {
  commands: ElementExport[];
  events: ElementExport[];
  views: ElementExport[];
} {
  const commands: ElementExport[] = [];
  const events: ElementExport[] = [];
  const views: ElementExport[] = [];
  const seenViews = new Set<string>();
  for (const slice of slices) {
    for (const el of slice.elements) {
      if (!el.public) continue;
      if (el.kind === "command") commands.push(el);
      else if (el.kind === "event") events.push(el);
      else if (el.kind === "view") {
        const key = el.name.trim().toLowerCase();
        if (seenViews.has(key)) continue;
        seenViews.add(key);
        views.push(el);
      }
    }
  }
  return { commands, events, views };
}

/**
 * Build the `em api generate` contract text. Same parameter contract as `buildExport`
 * (already-validated, error-free model; `path` is the `.em` file's real path, used for the doc
 * join); `sourceLabel` is the `Source:` line's path (defaults to `path`).
 */
export function buildApiContract(
  model: NormalizedModel,
  refs: RefsResult,
  diagnostics: Diagnostic[],
  source: string,
  path: string,
  sourceLabel: string = path,
): ApiContractResult {
  const { doc, diagnostics: allDiagnostics } = buildExportDoc(model, refs, diagnostics, source, path);
  const typesByRef = new Map(doc.model.types.map((t) => [t.ref, t]));
  const surface = publicSurfaceOf(doc.model.slices);

  // Declared types reachable (transitively) from a public element's fields.
  const reachable = reachableTypeRefs([...surface.commands, ...surface.events, ...surface.views], typesByRef);

  const usedNames = new Set<string>();
  const typeNameByRef = new Map<string, string>();
  for (const t of doc.model.types) {
    if (reachable.has(t.ref)) typeNameByRef.set(t.ref, dedupe(pascalCase(t.name), usedNames, "_"));
  }

  // GH #477: identity scalars reachable from the public surface, named through the SAME
  // `usedNames` dedup set as types/events/views/commands (one TypeSpec namespace, one set of
  // identifiers — a scalar named the same as a model/event would otherwise silently collide),
  // allocated up front in declaration order like `typeNameByRef` above (not at first use —
  // scalars never nest, so there's no walk-order dependency, but staying consistent with the
  // type precedent keeps this predictable too).
  const reachableScalars = reachableScalarRefs([...surface.commands, ...surface.events, ...surface.views], typesByRef);
  const scalarNameByRef = new Map<string, string>();
  for (const s of doc.model.scalars) {
    if (reachableScalars.has(s.ref)) scalarNameByRef.set(s.ref, dedupe(pascalCase(s.name), usedNames, "_"));
  }

  // GH #478: declared enums reachable from the public surface, named through the SAME
  // `usedNames` dedup set, same allocate-up-front-in-declaration-order posture as scalars above.
  const reachableEnums = reachableEnumRefs([...surface.commands, ...surface.events, ...surface.views], typesByRef);
  const enumNameByRef = new Map<string, string>();
  for (const e of doc.model.enums) {
    if (reachableEnums.has(e.ref)) enumNameByRef.set(e.ref, dedupe(pascalCase(e.name), usedNames, "_"));
  }

  // GH #444 (#443 ask 1): which table entries this contract actually uses, so the namespace
  // declares exactly the scalars its own fields need — never a dead declaration. GH #477: an
  // identity scalar's own base counts as "used" too (via the branch below), so the base's
  // table scalar declaration (e.g. `Uuid`) co-emits even when no field uses the bare table type.
  const usedScalars = new Set<string>();

  const fieldType = (f: FieldExport, owner: string): string => {
    if (f.typeRef) {
      const name = typeNameByRef.get(f.typeRef.ref) ?? pascalCase(f.typeRef.name);
      return f.typeRef.array ? `${name}[]` : name;
    }
    if (f.scalarRef) {
      const name = scalarNameByRef.get(f.scalarRef.ref) ?? pascalCase(f.scalarRef.name);
      usedScalars.add(f.scalarRef.base);
      return f.scalarRef.array ? `${name}[]` : name;
    }
    if (f.enumRef) {
      const name = enumNameByRef.get(f.enumRef.ref) ?? pascalCase(f.enumRef.name);
      return f.enumRef.array ? `${name}[]` : name;
    }
    const r = resolvePublicType(f.type ?? undefined, model.typesByName, model.scalarsByName, model.enumsByName);
    if (!r || r.kind !== "scalar") {
      throw new Error(
        `em api generate: ${owner} field "${f.name}" has no public type — em validate's public-field-type-unresolved should have refused this model`,
      );
    }
    usedScalars.add(r.scalar);
    return r.array ? `${r.tsType}[]` : r.tsType;
  };

  const member = (f: FieldExport, owner: string) =>
    `${fieldIdentifier(f.name)}${f.optional ? "?" : ""}: ${fieldType(f, owner)}`;

  const docBlock = (notes: string[]): string[] => ["/**", ...notes.map((n) => ` * ${n}`), " */"];

  const renderModel = (
    name: string,
    fields: FieldExport[] | null,
    owner: string,
    notes: string[],
    invariants: string[] = [],
  ): string => {
    const lines = docBlock([CONSUMER_TOLERANCE_SENTENCE, ...notes]);
    const body: string[] = [...invariants];
    for (const f of fields ?? []) {
      const n = fieldNotes(f);
      if (n) body.push(`/** ${n} */`);
      body.push(`${member(f, owner)};`);
    }
    lines.push(body.length > 0 ? `model ${name} {` : `model ${name} {}`);
    if (body.length > 0) lines.push(...indent(body, 1), "}");
    return lines.join("\n");
  };

  const sections: string[] = [];

  const typeBlocks: string[] = [];
  for (const t of doc.model.types) {
    const name = typeNameByRef.get(t.ref);
    if (name) typeBlocks.push(renderModel(name, t.fields, `type "${t.name}"`, []));
  }
  if (typeBlocks.length > 0) sections.push(typeBlocks.join("\n\n"));

  // GH #446: an event op's payload reuses the exact model name chosen above for its `model`
  // block — never re-derived — so the op always points at the declaration a binding file would
  // `@@channel`/`@@publish` against. Op names dedupe through their own set (like `opNames` does
  // for commands), even though in practice they can only collide if the (already-deduped) model
  // names do too.
  const eventBlocks: string[] = [];
  const eventNames: string[] = [];
  for (const el of surface.events) {
    const name = dedupe(pascalCase(el.name), usedNames, "_");
    eventNames.push(name);
    eventBlocks.push(renderModel(name, el.fields, `event "${el.name}"`, elementNotes(el), invariantLines(el)));
  }
  if (eventBlocks.length > 0) sections.push(eventBlocks.join("\n\n"));

  const eventOpNames = new Set<string>();
  const eventOps: string[] = [];
  for (const name of eventNames) {
    const opName = dedupe(`on${name}`, eventOpNames, "_");
    eventOps.push(`op ${opName}(payload: ${name}): void;`);
  }
  if (eventOps.length > 0) sections.push(["interface Events {", ...indent(eventOps, 1), "}"].join("\n"));

  const viewBlocks: string[] = [];
  const viewOps: string[] = [];
  for (const el of surface.views) {
    const name = dedupe(pascalCase(el.name), usedNames, "_");
    viewBlocks.push(renderModel(name, el.fields, `view "${el.name}"`, elementNotes(el), invariantLines(el)));
    viewOps.push(`op get${name}(): ${name};`);
  }
  if (viewBlocks.length > 0) {
    sections.push(viewBlocks.join("\n\n"));
    sections.push(["interface Views {", ...indent(viewOps, 1), "}"].join("\n"));
  }

  // GH #445 (#443 ask 2): a command's payload rides the same `renderModel` path as an event's or
  // a view's — so field notes and `INV-*` lines live on the payload model, the same home
  // events/views already use, not the op. That is also what makes the fields decoratable at
  // all: TypeSpec `@@` augment decorators target models and model properties, never positional
  // op parameters.
  const opNames = new Set<string>();
  const commandModelBlocks: string[] = [];
  const commandOps: string[] = [];
  for (const el of surface.commands) {
    const opName = dedupe(camelCase(pascalCase(el.name)), opNames, "_");
    const payloadName = dedupe(pascalCase(el.name), usedNames, "_");
    commandModelBlocks.push(
      renderModel(payloadName, el.fields, `command "${el.name}"`, elementNotes(el), invariantLines(el)),
    );
    commandOps.push(`op ${opName}(payload: ${payloadName}): void;`);
  }
  if (commandModelBlocks.length > 0) sections.push(commandModelBlocks.join("\n\n"));
  if (commandOps.length > 0) sections.push(["interface Commands {", ...indent(commandOps, 1), "}"].join("\n"));

  // Scalar declarations go first, in table order (not order of first use) — every field type
  // above is already computed by this point, so `usedScalars` is complete. GH #477: identity
  // scalars follow, in DECLARATION order, each extending either the formatted table scalar
  // (`scalar OrderId extends Uuid;`, the table entry's own `tsType` when it has a `scalarDecl`)
  // or the bare core type (`scalar Sku extends string;`) — `PublicTypeResolution`'s `identity`
  // kind and `ScalarExport.base` both already resolve to the table KEY, not the TypeSpec name,
  // so `PUBLIC_SCALAR_TYPES[s.base].tsType` is the one lookup that picks the right target either
  // way. Pinned by test: a model declaring no `scalar` contributes nothing here — byte-identical
  // to before GH #477.
  const scalarDecls: string[] = [];
  for (const name of PUBLIC_SCALAR_TYPE_NAMES) {
    if (!usedScalars.has(name)) continue;
    const decl = PUBLIC_SCALAR_TYPES[name].scalarDecl;
    if (decl) scalarDecls.push(decl);
  }
  for (const s of doc.model.scalars) {
    const name = scalarNameByRef.get(s.ref);
    if (!name) continue; // not reachable from the public surface — no dead declaration
    scalarDecls.push(`scalar ${name} extends ${PUBLIC_SCALAR_TYPES[s.base].tsType};`);
  }

  // GH #478: a reachable enum emits once, members in declaration order, right after the scalar
  // declarations and ahead of the type blocks (the two unshifts below, called in this order,
  // land the sections as [scalars, enums, types, …]). Members join on a single line like the
  // issue's own example (`enum OrderStatus { placed, shipped }`) — joined with ", " since every
  // member is short; a bare identifier emits unquoted, anything else as a quoted string literal
  // (`enumMemberText`). Pinned by test: a model declaring no `enum` contributes nothing here.
  const enumBlocks: string[] = [];
  for (const e of doc.model.enums) {
    const name = enumNameByRef.get(e.ref);
    if (!name) continue; // not reachable from the public surface — no dead declaration
    enumBlocks.push(`enum ${name} { ${e.members.map(enumMemberText).join(", ")} }`);
  }
  if (enumBlocks.length > 0) sections.unshift(enumBlocks.join("\n"));

  if (scalarDecls.length > 0) sections.unshift(scalarDecls.join("\n"));

  const namespaceName = pascalCase(doc.model.name ?? "Model");
  const header = [
    API_HEADER_LINE,
    `// Source: ${sourceLabel}`,
    "// Scope: the model's `public` commands (write API), events (async) and views (read API).",
  ];
  const body = sections.length > 0 ? indent(sections.join("\n\n").split("\n"), 1) : [];
  const ns = body.length > 0 ? [`namespace ${namespaceName} {`, ...body, "}"] : [`namespace ${namespaceName} {}`];
  return { text: [...header, "", ...ns].join("\n"), diagnostics: allDiagnostics };
}
