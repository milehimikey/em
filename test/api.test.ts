// ---- additive / breaking classification (R8) ------------------------------------------

const surface = (src: string) => {
  const c = compile(src);
  const doc = buildExportDoc(c.model, c.refs, c.diagnostics, src, "m.em").doc;
  return surfaceOf(doc.model.slices, doc.model.types);
};
const changes = (before: string, after: string) => diffSurfaces(surface(before), surface(after));
const ev = (fields: string) => `slice "S" {\n  command Do public { x: string }\n  event Done @D public { ${fields} }\n}\n`;
const cmd = (fields: string) => `slice "S" {\n  command Do public { ${fields} }\n  event Done @D\n}\n`;

describe("diffSurfaces", () => {
  it("output field removed = breaking; output field added (required or optional) = additive", () => {
    expect(changes(ev("a: string, b: string"), ev("a: string"))).toEqual([
      { kind: "breaking", element: "event.done", field: "b", what: "removed" },
    ]);
    expect(changes(ev("a: string"), ev("a: string, b: string, c?: string"))).toEqual([
      { kind: "additive", element: "event.done", field: "b", what: "added (required)" },
      { kind: "additive", element: "event.done", field: "c", what: "added (optional)" },
    ]);
  });

  it("output field required → optional = breaking; optional → required = breaking", () => {
    expect(changes(ev("a: string"), ev("a?: string"))).toEqual([
      { kind: "breaking", element: "event.done", field: "a", what: "changed required → optional" },
    ]);
    expect(changes(ev("a?: string"), ev("a: string"))).toEqual([
      { kind: "breaking", element: "event.done", field: "a", what: "changed optional → required" },
    ]);
  });

  it("command input: required field added = breaking, optional added = additive, required → optional = additive", () => {
    expect(changes(cmd("x: string"), cmd("x: string, y: string, z?: string"))).toEqual([
      { kind: "breaking", element: "command.do", field: "y", what: "added (required)" },
      { kind: "additive", element: "command.do", field: "z", what: "added (optional)" },
    ]);
    expect(changes(cmd("x: string"), cmd("x?: string"))).toEqual([
      { kind: "additive", element: "command.do", field: "x", what: "changed required → optional" },
    ]);
  });

  it("field renamed (`renamed from`) = breaking; type changed = breaking", () => {
    expect(changes(ev("a: string"), ev('b: string renamed from "a"'))).toEqual([
      { kind: "breaking", element: "event.done", field: "b", what: 'renamed from "a"' },
    ]);
    expect(changes(ev("a: string"), ev("a: int"))).toEqual([
      { kind: "breaking", element: "event.done", field: "a", what: "type changed string → int" },
    ]);
  });

  it("element added / marked public = additive; removed / renamed / `public` dropped = breaking", () => {
    const base = `slice "S" {\n  command Do public\n  event Done @D public\n}\n`;
    expect(changes(base, `slice "S" {\n  command Do public\n  event Done @D public\n  event Also @D public\n}\n`)).toEqual([
      { kind: "additive", element: "event.also", field: null, what: "added" },
    ]);
    expect(changes(`slice "S" {\n  command Do\n  event Done @D public\n}\n`, base)).toEqual([
      { kind: "additive", element: "command.do", field: null, what: "marked public" },
    ]);
    expect(changes(base, `slice "S" {\n  command Do public\n  event Done @D\n}\n`)).toEqual([
      { kind: "breaking", element: "event.done", field: null, what: "`public` dropped" },
    ]);
    expect(changes(base, `slice "S" {\n  command Do public\n}\n`)).toEqual([
      { kind: "breaking", element: "event.done", field: null, what: "removed" },
    ]);
    expect(changes(base, `slice "S" {\n  command Do public\n  event Finished renamed from "Done" @D public\n}\n`)).toEqual([
      { kind: "breaking", element: "event.finished", field: null, what: 'renamed from "Done"' },
    ]);
  });

  it("diffs declared types reachable from the public surface", () => {
    const t = (fields: string) => `type Money2 { ${fields} }\nslice "S" {\n  command Do\n  event Done @D public { m: Money2 }\n}\n`;
    expect(changes(t("cents: long, cur: string"), t("cents: long"))).toEqual([
      { kind: "breaking", element: "type.money2", field: "cur", what: "removed" },
    ]);
  });

  it("a model absent at base reports every public element additive", () => {
    expect(diffSurfaces(null, surface(ev("a: string")))).toEqual([
      { kind: "additive", element: "command.do", field: null, what: "added" },
      { kind: "additive", element: "event.done", field: null, what: "added" },
    ]);
  });
});

