// ---- Optional compile-verification (skip-if-absent) ------------------------------------
//
// `@typespec/compiler` is a devDependency only; it needs Node >= its own `engines.node`
// (CI runs Node 20), so this block skips rather than fails when that isn't met.
const TSP_BIN = join(ROOT, "node_modules", ".bin", "tsp");

function nodeSatisfiesEngineRequirement(pkgDir: string): boolean {
  try {
    const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")) as { engines?: { node?: string } };
    const required = pkg.engines?.node;
    const minMajor = required ? Number(required.match(/(\d+)/)?.[1] ?? 0) : 0;
    return Number(process.versions.node.split(".")[0]) >= minMajor;
  } catch {
    return false;
  }
}

const TSP_AVAILABLE = existsSync(TSP_BIN) && nodeSatisfiesEngineRequirement(join(ROOT, "node_modules", "@typespec", "compiler"));

function tspCompile(text: string): { status: number | null; out: string } {
  const dir = mkdtempSync(join(tmpdir(), "em-tsp-"));
  try {
    const file = join(dir, "main.tsp");
    writeFileSync(file, text);
    const res = spawnSync(process.execPath, [TSP_BIN, "compile", file, "--no-emit"], { encoding: "utf8" });
    return { status: res.status, out: `${res.stdout ?? ""}\n${res.stderr ?? ""}` };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

